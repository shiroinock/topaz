#!/usr/bin/env node
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

const inputPath = "runtime/runtime.h";
const outputPath = "src/runtime_header.ts";
const chunkSize = 1800;

function sanitizeRuntimeHeader(text) {
  // Topaz string literals are ASCII-only. Non-ASCII bytes in runtime.h are
  // comments today, so make the embedded copy ASCII without changing code.
  return text.replace(/[^\x00-\x7f]/g, "?");
}

function escapeTsString(text) {
  let out = "\"";
  for (let i = 0; i < text.length; i++) {
    const c = text.charCodeAt(i);
    if (c === 0x22) out += "\\\"";
    else if (c === 0x5c) out += "\\\\";
    else if (c === 0x0a) out += "\\n";
    else if (c === 0x0d) out += "\\r";
    else if (c === 0x09) out += "\\t";
    else if (c === 0x00) out += "\\0";
    else if (c < 0x20 || c === 0x7f) out += `\\x${c.toString(16).padStart(2, "0")}`;
    else out += String.fromCharCode(c);
  }
  out += "\"";
  return out;
}

function chunkText(text) {
  const chunks = [];
  for (let i = 0; i < text.length; i += chunkSize) {
    chunks.push(text.slice(i, i + chunkSize));
  }
  return chunks;
}

export function renderRuntimeHeaderSource(runtimeHeaderText) {
  const chunks = chunkText(sanitizeRuntimeHeader(runtimeHeaderText));
  const lines = [
    "// Generated by scripts/generate-runtime-header.mjs from runtime/runtime.h.",
    "// Do not edit by hand.",
    "",
    "export function runtimeHeaderSource(): string {",
    "  return (",
  ];

  for (let i = 0; i < chunks.length; i++) {
    const suffix = i + 1 === chunks.length ? "" : " +";
    lines.push(`    ${escapeTsString(chunks[i])}${suffix}`);
  }

  lines.push("  );");
  lines.push("}");
  lines.push("");
  return lines.join("\n");
}

function expectedRuntimeHeaderSource() {
  return renderRuntimeHeaderSource(readFileSync(inputPath, "utf8"));
}

function writeRuntimeHeader() {
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, expectedRuntimeHeaderSource());
}

function checkRuntimeHeader() {
  const expected = expectedRuntimeHeaderSource();
  const actual = readFileSync(outputPath, "utf8");
  if (actual !== expected) {
    console.error(
      `${outputPath} is stale. Run pnpm run generate:runtime-header and commit the updated file.`,
    );
    process.exitCode = 1;
    return;
  }
  console.log("runtime header is fresh");
}

const args = process.argv.slice(2);
if (args.length === 0) {
  writeRuntimeHeader();
} else if (args.length === 1 && args[0] === "--check") {
  checkRuntimeHeader();
} else {
  console.error("usage: node scripts/generate-runtime-header.mjs [--check]");
  process.exitCode = 1;
}
