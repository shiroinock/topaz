#!/usr/bin/env node
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

const inputPath = "runtime/runtime.h";
const outputPath = "src/runtime_header.ts";
const chunkSize = 1800;

function sanitizeRuntimeHeader(text) {
  // Topaz string literals are ASCII-only. Non-ASCII bytes in runtime.h are
  // comments today, so make the embedded copy ASCII without changing code.
  return text.replace(/[^\x00-\x7f]/g, "?");
}

function escapeTsString(text) {
  let out = "\"";
  for (let i = 0; i < text.length; i++) {
    const c = text.charCodeAt(i);
    if (c === 0x22) out += "\\\"";
    else if (c === 0x5c) out += "\\\\";
    else if (c === 0x0a) out += "\\n";
    else if (c === 0x0d) out += "\\r";
    else if (c === 0x09) out += "\\t";
    else if (c === 0x00) out += "\\0";
    else if (c < 0x20 || c === 0x7f) out += `\\x${c.toString(16).padStart(2, "0")}`;
    else out += String.fromCharCode(c);
  }
  out += "\"";
  return out;
}

const runtimeHeader = sanitizeRuntimeHeader(readFileSync(inputPath, "utf8"));
const chunks = [];
for (let i = 0; i < runtimeHeader.length; i += chunkSize) {
  chunks.push(runtimeHeader.slice(i, i + chunkSize));
}

const lines = [
  "// Generated by scripts/generate-runtime-header.mjs from runtime/runtime.h.",
  "// Do not edit by hand.",
  "",
  "export function runtimeHeaderSource(): string {",
  "  return (",
];

for (let i = 0; i < chunks.length; i++) {
  const suffix = i + 1 === chunks.length ? "" : " +";
  lines.push(`    ${escapeTsString(chunks[i])}${suffix}`);
}

lines.push("  );");
lines.push("}");
lines.push("");

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, lines.join("\n"));
