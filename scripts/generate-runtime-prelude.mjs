#!/usr/bin/env node
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

const inputPath = "runtime/prelude.ts";
const outputPath = "src/runtime_prelude.ts";
const chunkSize = 1800;

function escapeTsString(text) {
  let out = "\"";
  for (let i = 0; i < text.length; i++) {
    const c = text.charCodeAt(i);
    if (c === 0x22) out += "\\\"";
    else if (c === 0x5c) out += "\\\\";
    else if (c === 0x0a) out += "\\n";
    else if (c === 0x0d) out += "\\r";
    else if (c === 0x09) out += "\\t";
    else if (c === 0x00) out += "\\0";
    else if (c < 0x20 || c === 0x7f) out += `\\x${c.toString(16).padStart(2, "0")}`;
    else out += String.fromCharCode(c);
  }
  out += "\"";
  return out;
}

function chunkText(text) {
  const chunks = [];
  for (let i = 0; i < text.length; i += chunkSize) {
    chunks.push(text.slice(i, i + chunkSize));
  }
  return chunks;
}

export function renderRuntimePreludeSource(runtimePreludeText) {
  const chunks = chunkText(runtimePreludeText);
  const lines = [
    "// Generated by scripts/generate-runtime-prelude.mjs from runtime/prelude.ts.",
    "// Do not edit by hand.",
    "",
    "export function runtimePreludeSource(): string {",
    "  return (",
  ];

  for (let i = 0; i < chunks.length; i++) {
    const suffix = i + 1 === chunks.length ? "" : " +";
    lines.push(`    ${escapeTsString(chunks[i])}${suffix}`);
  }

  lines.push("  );");
  lines.push("}");
  lines.push("");
  return lines.join("\n");
}

function expectedRuntimePreludeSource() {
  return renderRuntimePreludeSource(readFileSync(inputPath, "utf8"));
}

function writeRuntimePrelude() {
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, expectedRuntimePreludeSource());
}

function checkRuntimePrelude() {
  const expected = expectedRuntimePreludeSource();
  const actual = readFileSync(outputPath, "utf8");
  if (actual !== expected) {
    console.error(
      `${outputPath} is stale. Run pnpm run generate:runtime-prelude and commit the updated file.`,
    );
    process.exitCode = 1;
    return;
  }
  console.log("runtime prelude is fresh");
}

const args = process.argv.slice(2);
if (args.length === 0) {
  writeRuntimePrelude();
} else if (args.length === 1 && args[0] === "--check") {
  checkRuntimePrelude();
} else {
  console.error("usage: node scripts/generate-runtime-prelude.mjs [--check]");
  process.exitCode = 1;
}
